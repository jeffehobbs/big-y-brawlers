function textWidth(str, scale){ return str.length * 6 * scale - scale; }
function drawText(g, str, x, y, scale, color, outline){
  scale = scale || 1;
  str = String(str).toUpperCase().replace(/[\u2014\u2013]/g, "-").replace(/[\u2018\u2019]/g, "'").replace(/[\u201c\u201d]/g, '"').replace(/\u2026/g, "...");
  const passes = outline
    ? [[-1,0,outline],[1,0,outline],[0,-1,outline],[0,1,outline],[0,0,color]]
    : [[0,0,color]];
  for (const [dx, dy, col] of passes){
    g.fillStyle = col;
    for (let i = 0; i < str.length; i++){
      const glyph = FONT5X7[str[i]] || FONT5X7["?"];
      for (let r = 0; r < 7; r++){
        for (let c = 0; c < 5; c++){
          if (glyph[r][c] === "1") g.fillRect(x + i*6*scale + c*scale + dx*scale, y + r*scale + dy*scale, scale, scale);
        }
      }
    }
  }
}
function drawTextC(g, str, cx, y, scale, color, outline){
  drawText(g, str, Math.round(cx - textWidth(str, scale)/2), y, scale, color, outline);
}
